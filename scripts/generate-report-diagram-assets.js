const fs = require('node:fs');
const path = require('node:path');
const { ESLint } = require('eslint');

const source = path.resolve(__dirname, '..', 'images', 'disaggregated');
const assets = Object.fromEntries(fs.readdirSync(source).filter(name => name.endsWith('.svg')).sort()
    .map(name => [name, fs.readFileSync(path.join(source, name), 'utf8').replace(/\r\n/g, '\n')]));

const destination = path.resolve(__dirname, '..', 'report', 'diagram-assets.js');
const content = '// Generated by scripts/generate-report-diagram-assets.js. Do not edit.\n' +
    'window.ODIN_REPORT_DIAGRAM_ASSETS = ' + JSON.stringify(assets, null, 4) + ';\n';
const eslint = new ESLint({ fix: true, cwd: path.resolve(__dirname, '..') });
eslint.lintText(content, { filePath: destination }).then(([result]) => {
    if (result.errorCount || result.warningCount) {
        throw new Error('Generated report diagram asset failed lint: ' + JSON.stringify(result.messages));
    }
    fs.writeFileSync(destination, result.output || content);
}).catch(error => {
    console.error(error);
    process.exitCode = 1;
});
