(function(global) {
    'use strict';

    const DEPLOYMENT_MODES = ['Validate', 'Deploy'];

    function requireDeploymentMode(mode) {
        if (!DEPLOYMENT_MODES.includes(mode)) {
            throw new Error('Deployment mode must be Validate or Deploy.');
        }
        return mode;
    }

    function parametersForMode(parametersFile, mode) {
        requireDeploymentMode(mode);
        if (!parametersFile || typeof parametersFile !== 'object' || !parametersFile.parameters) {
            throw new Error('An ARM parameters file is required.');
        }

        const result = JSON.parse(JSON.stringify(parametersFile));
        result.parameters.deploymentMode = result.parameters.deploymentMode || {};
        result.parameters.deploymentMode.value = mode;
        return result;
    }

    function buildPowerShellScript(options) {
        const location = requireDeploymentLocation(options && options.location);
        const tenantId = options.tenantId || '';
        const tenantVariable = tenantId ? `$tenantId = "${tenantId}"` : '# $tenantId = "your-tenant-id"';
        const tenantArgument = tenantId ? ' -TenantId $tenantId' : '';

        return `# Azure Local two-phase deployment script
# Generated by ODIN for Azure Local
# First run:  .\\deploy-azurelocal.ps1
# Second run: .\\deploy-azurelocal.ps1 -DeploymentMode Deploy

param(
    [ValidateSet('Validate', 'Deploy')]
    [string]$DeploymentMode = 'Validate'
)

$ErrorActionPreference = 'Stop'

${tenantVariable}
$subscriptionId = "${options.subscriptionId}"
$resourceGroupName = "${options.resourceGroupName}"
$deploymentName = "${options.deploymentName}"
$location = "${location}"
$templateFile = "azurelocal-template.json"
$parametersFile = "azurelocal-parameters-$($DeploymentMode.ToLowerInvariant()).json"

Connect-AzAccount${tenantArgument}
Set-AzContext -SubscriptionId $subscriptionId

$resourceGroup = Get-AzResourceGroup -Name $resourceGroupName -ErrorAction SilentlyContinue
if (-not $resourceGroup) {
    if ($DeploymentMode -eq 'Deploy') {
        throw 'The resource group does not exist. Run the Validate deployment first.'
    }
    New-AzResourceGroup -Name $resourceGroupName -Location $location
}

$parameterDocument = Get-Content -LiteralPath $parametersFile -Raw | ConvertFrom-Json
$clusterName = [string]$parameterDocument.parameters.clusterName.value

if ($DeploymentMode -eq 'Deploy') {
    if ([string]::IsNullOrWhiteSpace($clusterName) -or $clusterName -like 'REPLACE_WITH_*') {
        throw 'Set clusterName in the parameters file before running Deploy.'
    }

    $clusterLookup = @{
        ResourceGroupName = $resourceGroupName
        ResourceType = 'Microsoft.AzureStackHCI/clusters'
        Name = $clusterName
        ErrorAction = 'SilentlyContinue'
    }
    $cluster = Get-AzResource @clusterLookup
    if (-not $cluster) {
        throw 'The Azure Local cluster resource is missing. Complete the Validate deployment in this resource group before running Deploy.'
    }
}

Write-Host "Starting the Azure Local $DeploymentMode deployment."
$deploymentParameters = @{
    Name = $deploymentName
    ResourceGroupName = $resourceGroupName
    TemplateFile = $templateFile
    TemplateParameterFile = $parametersFile
    deploymentMode = $DeploymentMode
    Mode = 'Incremental'
    Verbose = $true
}
New-AzResourceGroupDeployment @deploymentParameters

if ($DeploymentMode -eq 'Validate') {
    Write-Host 'Validate deployment completed. Review its result, then rerun this script with -DeploymentMode Deploy.'
} else {
    Write-Host 'Deploy deployment completed successfully.'
}
`;
    }

    function buildAzureCliScript(options) {
        const location = requireDeploymentLocation(options && options.location);
        const tenantId = options.tenantId || '';
        const tenantVariable = tenantId ? `TENANT_ID="${tenantId}"` : '# TENANT_ID="your-tenant-id"';
        const tenantArgument = tenantId ? ' --tenant "$TENANT_ID"' : '';

        return `#!/usr/bin/env bash
# Azure Local two-phase deployment script
# Generated by ODIN for Azure Local
# First run:  ./deploy-azurelocal.sh
# Second run: ./deploy-azurelocal.sh Deploy

set -euo pipefail

DEPLOYMENT_MODE="\${1:-Validate}"
if [[ "$DEPLOYMENT_MODE" != "Validate" && "$DEPLOYMENT_MODE" != "Deploy" ]]; then
    echo "Deployment mode must be Validate or Deploy." >&2
    exit 2
fi

${tenantVariable}
SUBSCRIPTION_ID="${options.subscriptionId}"
RESOURCE_GROUP="${options.resourceGroupName}"
DEPLOYMENT_NAME="${options.deploymentName}"
LOCATION="${location}"
TEMPLATE_FILE="azurelocal-template.json"
PARAMETERS_FILE="azurelocal-parameters-\${DEPLOYMENT_MODE,,}.json"

az login${tenantArgument}
az account set --subscription "$SUBSCRIPTION_ID"

if [[ "$DEPLOYMENT_MODE" == "Validate" ]]; then
    groupExists=$(az group exists --name "$RESOURCE_GROUP")
    if [[ "$groupExists" == "false" ]]; then
        az group create --name "$RESOURCE_GROUP" --location "$LOCATION"
    fi
elif ! az group show --name "$RESOURCE_GROUP" --only-show-errors >/dev/null 2>&1; then
    echo "The resource group does not exist. Run the Validate deployment first." >&2
    exit 1
fi

if [[ "$DEPLOYMENT_MODE" == "Deploy" ]]; then
    clusterName=$(jq -r '.parameters.clusterName.value // empty' "$PARAMETERS_FILE")
    if [[ -z "$clusterName" || "$clusterName" == REPLACE_WITH_* ]]; then
        echo "Set clusterName in $PARAMETERS_FILE before running Deploy." >&2
        exit 1
    fi
    if ! az resource show \
        --resource-group "$RESOURCE_GROUP" \
        --resource-type 'Microsoft.AzureStackHCI/clusters' \
        --name "$clusterName" \
        --only-show-errors >/dev/null 2>&1; then
        echo "The Azure Local cluster resource is missing. Complete the Validate deployment in this resource group before running Deploy." >&2
        exit 1
    fi
fi

echo "Running ARM What-If preflight. This does not perform Azure Local Validate mode."
az deployment group what-if \
    --name "$DEPLOYMENT_NAME" \
    --resource-group "$RESOURCE_GROUP" \
    --template-file "$TEMPLATE_FILE" \
    --parameters "@$PARAMETERS_FILE" deploymentMode="$DEPLOYMENT_MODE"

echo "Starting the Azure Local $DEPLOYMENT_MODE deployment."
az deployment group create \
    --name "$DEPLOYMENT_NAME" \
    --resource-group "$RESOURCE_GROUP" \
    --template-file "$TEMPLATE_FILE" \
    --parameters "@$PARAMETERS_FILE" deploymentMode="$DEPLOYMENT_MODE" \
    --mode Incremental \
    --verbose

if [[ "$DEPLOYMENT_MODE" == "Validate" ]]; then
    echo "Validate deployment completed. Review its result, then rerun this script with Deploy."
else
    echo "Deploy deployment completed successfully."
fi
`;
    }

    function requireDeploymentLocation(location) {
        if (typeof location !== 'string' || !/^[a-z][a-z0-9]*$/.test(location)) {
            throw new Error('A valid Azure region code is required (for example, westeurope).');
        }
        return location;
    }

    function buildAzureDevOpsPipeline(options) {
        const location = requireDeploymentLocation(options && options.location);
        return `# Azure Local two-phase deployment pipeline
# Generated by ODIN for Azure Local
# Replace azureServiceConnection with an Azure Resource Manager service connection
# authorized for this pipeline and the target subscription.

trigger: none

parameters:
- name: deploymentMode
  displayName: Azure Local deployment phase
  type: string
  default: Validate
  values:
  - Validate
  - Deploy

pool:
  vmImage: 'ubuntu-latest'

variables:
  azureServiceConnection: 'REPLACE_WITH_AZURE_SERVICE_CONNECTION_NAME'
  resourceGroupName: 'REPLACE_WITH_RESOURCE_GROUP_NAME'
  location: '${location}'
  deploymentName: 'azurelocal-deployment'
  templateFile: 'azurelocal-template.json'
  validateParametersFile: 'azurelocal-parameters-validate.json'
  deployParametersFile: 'azurelocal-parameters-deploy.json'

stages:
- stage: Validate
  displayName: 'Run Azure Local Validate deployment'
  condition: eq('\${{ parameters.deploymentMode }}', 'Validate')
  jobs:
  - job: ValidateJob
    steps:
    - task: AzureCLI@2
      displayName: 'Ensure resource group exists'
      inputs:
        azureSubscription: '$(azureServiceConnection)'
        scriptType: 'bash'
        scriptLocation: 'inlineScript'
        inlineScript: |
          set -euo pipefail
          groupExists=$(az group exists --name "$(resourceGroupName)")
          if [[ "$groupExists" == "false" ]]; then
            az group create --name "$(resourceGroupName)" --location "$(location)"
          fi
    - task: AzureCLI@2
      displayName: 'ARM What-If preflight (not Azure Local validation)'
      inputs:
        azureSubscription: '$(azureServiceConnection)'
        scriptType: 'bash'
        scriptLocation: 'inlineScript'
        inlineScript: |
          az deployment group what-if \
            --name "$(deploymentName)" \
            --resource-group "$(resourceGroupName)" \
            --template-file "$(templateFile)" \
            --parameters "@$(validateParametersFile)" deploymentMode=Validate
    - task: AzureCLI@2
      displayName: 'Create Azure Local Validate deployment'
      inputs:
        azureSubscription: '$(azureServiceConnection)'
        scriptType: 'bash'
        scriptLocation: 'inlineScript'
        inlineScript: |
          az deployment group create \
            --name "$(deploymentName)" \
            --resource-group "$(resourceGroupName)" \
            --template-file "$(templateFile)" \
            --parameters "@$(validateParametersFile)" deploymentMode=Validate \
            --mode Incremental

- stage: Deploy
  displayName: 'Run Azure Local Deploy deployment'
  condition: eq('\${{ parameters.deploymentMode }}', 'Deploy')
  jobs:
  - deployment: DeployJob
    environment: 'production'
    strategy:
      runOnce:
        deploy:
          steps:
          - checkout: self
          - task: AzureCLI@2
            displayName: 'Verify Validate created the cluster resource'
            inputs:
              azureSubscription: '$(azureServiceConnection)'
              scriptType: 'bash'
              scriptLocation: 'inlineScript'
              inlineScript: |
                clusterName=$(jq -r '.parameters.clusterName.value // empty' "$(deployParametersFile)")
                if [[ -z "$clusterName" || "$clusterName" == REPLACE_WITH_* ]]; then
                  echo "Set clusterName in $(deployParametersFile) before running Deploy." >&2
                  exit 1
                fi
                az resource show \
                  --resource-group "$(resourceGroupName)" \
                  --resource-type 'Microsoft.AzureStackHCI/clusters' \
                  --name "$clusterName" \
                  --only-show-errors >/dev/null
          - task: AzureCLI@2
            displayName: 'ARM What-If preflight (not Azure Local validation)'
            inputs:
              azureSubscription: '$(azureServiceConnection)'
              scriptType: 'bash'
              scriptLocation: 'inlineScript'
              inlineScript: |
                az deployment group what-if \
                  --name "$(deploymentName)" \
                  --resource-group "$(resourceGroupName)" \
                  --template-file "$(templateFile)" \
                  --parameters "@$(deployParametersFile)" deploymentMode=Deploy
          - task: AzureCLI@2
            displayName: 'Create Azure Local Deploy deployment'
            inputs:
              azureSubscription: '$(azureServiceConnection)'
              scriptType: 'bash'
              scriptLocation: 'inlineScript'
              inlineScript: |
                az deployment group create \
                  --name "$(deploymentName)" \
                  --resource-group "$(resourceGroupName)" \
                  --template-file "$(templateFile)" \
                  --parameters "@$(deployParametersFile)" deploymentMode=Deploy \
                  --mode Incremental
`;
    }

    function buildGitHubWorkflow(options) {
        const location = requireDeploymentLocation(options && options.location);
        return `# Azure Local two-phase deployment workflow
# Generated by ODIN for Azure Local

name: Deploy Azure Local

on:
  workflow_dispatch:
    inputs:
      deploymentMode:
        description: 'Run Validate first; select Deploy only after Validate succeeds'
        required: true
        default: Validate
        type: choice
        options:
        - Validate
        - Deploy

permissions:
  contents: read

env:
  RESOURCE_GROUP: REPLACE_WITH_RESOURCE_GROUP_NAME
  LOCATION: ${location}
  DEPLOYMENT_NAME: azurelocal-deployment
  TEMPLATE_FILE: azurelocal-template.json
  VALIDATE_PARAMETERS_FILE: azurelocal-parameters-validate.json
  DEPLOY_PARAMETERS_FILE: azurelocal-parameters-deploy.json

jobs:
  validate:
    name: Run Azure Local Validate deployment
    if: \${{ inputs.deploymentMode == 'Validate' }}
    runs-on: ubuntu-latest
    steps:
      - name: Checkout code
        uses: actions/checkout@v4
      - name: Azure login
        uses: azure/login@v2
        with:
          creds: \${{ secrets.AZURE_CREDENTIALS }}
      - name: Ensure resource group exists
        run: |
          set -euo pipefail
          groupExists=$(az group exists --name "$RESOURCE_GROUP")
          if [[ "$groupExists" == "false" ]]; then
            az group create --name "$RESOURCE_GROUP" --location "$LOCATION"
          fi
      - name: ARM What-If preflight (not Azure Local validation)
        run: |
          az deployment group what-if \
            --name "$DEPLOYMENT_NAME" \
            --resource-group "$RESOURCE_GROUP" \
            --template-file "$TEMPLATE_FILE" \
            --parameters "@$VALIDATE_PARAMETERS_FILE" deploymentMode=Validate
      - name: Create Azure Local Validate deployment
        run: |
          az deployment group create \
            --name "$DEPLOYMENT_NAME" \
            --resource-group "$RESOURCE_GROUP" \
            --template-file "$TEMPLATE_FILE" \
            --parameters "@$VALIDATE_PARAMETERS_FILE" deploymentMode=Validate \
            --mode Incremental

  deploy:
    name: Run Azure Local Deploy deployment
    if: \${{ inputs.deploymentMode == 'Deploy' }}
    runs-on: ubuntu-latest
    environment: production
    steps:
      - name: Checkout code
        uses: actions/checkout@v4
      - name: Azure login
        uses: azure/login@v2
        with:
          creds: \${{ secrets.AZURE_CREDENTIALS }}
      - name: Verify Validate created the cluster resource
        run: |
          clusterName=$(jq -r '.parameters.clusterName.value // empty' "$DEPLOY_PARAMETERS_FILE")
          if [[ -z "$clusterName" || "$clusterName" == REPLACE_WITH_* ]]; then
            echo "Set clusterName in $DEPLOY_PARAMETERS_FILE before running Deploy." >&2
            exit 1
          fi
          az resource show \
            --resource-group "$RESOURCE_GROUP" \
            --resource-type 'Microsoft.AzureStackHCI/clusters' \
            --name "$clusterName" \
            --only-show-errors >/dev/null
      - name: ARM What-If preflight (not Azure Local validation)
        run: |
          az deployment group what-if \
            --name "$DEPLOYMENT_NAME" \
            --resource-group "$RESOURCE_GROUP" \
            --template-file "$TEMPLATE_FILE" \
            --parameters "@$DEPLOY_PARAMETERS_FILE" deploymentMode=Deploy
      - name: Create Azure Local Deploy deployment
        run: |
          az deployment group create \
            --name "$DEPLOYMENT_NAME" \
            --resource-group "$RESOURCE_GROUP" \
            --template-file "$TEMPLATE_FILE" \
            --parameters "@$DEPLOY_PARAMETERS_FILE" deploymentMode=Deploy \
            --mode Incremental
`;
    }

    global.ArmDeploymentWorkflow = Object.freeze({
        requireDeploymentLocation: requireDeploymentLocation,
        parametersForMode: parametersForMode,
        buildPowerShellScript: buildPowerShellScript,
        buildAzureCliScript: buildAzureCliScript,
        buildAzureDevOpsPipeline: buildAzureDevOpsPipeline,
        buildGitHubWorkflow: buildGitHubWorkflow
    });
})(typeof window !== 'undefined' ? window : globalThis);